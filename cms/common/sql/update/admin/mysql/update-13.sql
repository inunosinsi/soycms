CREATE TABLE NotFoundLog(
	ipAddressId INTEGER UNSIGNED NOT NULL,
	requestUriId INTEGER UNSIGNED NOT NULL,
	cdate INTEGER UNSIGNED NOT NULL,
	UNIQUE(ipAddressId, requestUriId, cdate)
) ENGINE=InnoDB;

CREATE TABLE IpAddress(
	id INTEGER PRIMARY KEY AUTO_INCREMENT,
	v4 INT UNSIGNED NOT NULL UNIQUE,
	is_suspicious TINYINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE RequestUri(
	id INTEGER PRIMARY KEY AUTO_INCREMENT,
	uri TEXT NOT NULL,
	hash BINARY(16) NOT NULL UNIQUE
) ENGINE=InnoDB;
